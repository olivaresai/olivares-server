//go:build linux

package entitled

import (
	"io/fs"
	"syscall"
)

// ownerUID is the user id the kernel reports for info; false when it reports none.
func ownerUID(info fs.FileInfo) (int, bool) {
	st, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, false
	}
	return int(st.Uid), true
}
